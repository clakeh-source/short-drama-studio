function requireSeries(seriesId: string | null | undefined): string {
  if (!seriesId) {
    throw new NonRetriableError('This run has no series yet — the bible stage did not finish.');
  }
  return seriesId;
}

function previousStage(stage: RunStage): RunStage {
  const order: RunStage[] = ['bible', 'cast', 'script', 'storyboard', 'shots', 'assemble', 'done'];
  const index = order.indexOf(stage);
  return order[index - 1] ?? 'bible';
}

async function firstEpisodeId(seriesId: string): Promise<string> {
  const [row] = await db()
    .select({ id: episodes.id })
    .from(episodes)
    .where(eq(episodes.seriesId, seriesId));
  if (!row) throw new NonRetriableError('This run has no episode to work on.');
  return row.id;
}

/** Creates the series and develops the bible, cast and episode stubs. */
async function runBibleStage(
  runId: string,
  userId: string,
  prompt: string,
  targetSeconds: number,
): Promise<string> {
  const [row] = await db()
    .insert(series)
    .values({
      userId,
      // Placeholders until the bible names the show.
      title: prompt.slice(0, 60),
      logline: prompt,
      episodeTargetCount: 1,
      episodeTargetSeconds: targetSeconds,
      status: 'draft',
    })
    .returning({ id: series.id });

  const seriesId = row!.id;
  await updateRun(runId, { seriesId });

  const result = await generateBible({
    provider: getLlmProvider(),
    input: {
      premise: prompt,
      genre: '',
      tone: '',
      audience: '',
      language: 'en',
      episodeCount: 1,
      episodeSeconds: targetSeconds,
    },
  });

  await persistBible(userId, seriesId, result.data);
  await recordStageResult(runId, 'bible', {
    title: result.data.title,
    logline: result.data.logline,
    characters: result.data.characters.map((c) => c.name),
    costCents: result.usage.costCents,
  });

  return seriesId;
}

/** Draws every character, so the shots can be image-to-video. */
async function runCastStage(runId: string, userId: string, seriesId: string): Promise<string> {
  const result = await generateMissingPortraits(userId, seriesId);

  await recordStageResult(runId, 'cast', {
    generated: result.generated.map((g) => ({ name: g.characterName, stills: g.generated })),
    skipped: result.skipped,
    costCents: result.costCents,
  });

  return seriesId;
}

async function runScriptStage(runId: string, userId: string, seriesId: string): Promise<string> {
  const episodeId = await firstEpisodeId(seriesId);
  const { episode, series: seriesRow } = await loadEpisode(userId, episodeId);

  const bible = parseBible(seriesRow.bible);
  if (!bible) throw new NonRetriableError('The bible stage produced nothing usable.');

  const result = await generateScript({
    provider: getLlmProvider(),
    bible,
    episodeNumber: episode.number,
    episodeSeconds: seriesRow.episodeTargetSeconds,
    language: seriesRow.language,
  });

  await persistScript(userId, episodeId, result.data);
  await recordStageResult(runId, 'script', {
    hook: result.data.hook,
    scenes: result.data.scenes.length,
    costCents: result.usage.costCents,
  });

  return seriesId;
}

async function runStoryboardStage(
  runId: string,
  userId: string,
  seriesId: string,
): Promise<string> {
  const episodeId = await firstEpisodeId(seriesId);
  const { episode, series: seriesRow } = await loadEpisode(userId, episodeId);

  const bible = parseBible(seriesRow.bible);
  const script = parseScript(episode.script);
  if (!bible || !script) {
    throw new NonRetriableError('The script stage produced nothing to storyboard.');
  }

  const video = getVideoProvider();
  const result = await generateStoryboard({
    provider: getLlmProvider(),
    bible,
    script,
    episodeNumber: episode.number,
    episodeSeconds: seriesRow.episodeTargetSeconds,
  });

  const persisted = await persistStoryboard({
    userId,
    episodeId,
    bible,
    script,
    storyboard: result.data,
    episodeSeconds: seriesRow.episodeTargetSeconds,
    clampDuration: (seconds) => video.clampDuration(seconds),
  });

  await recordStageResult(runId, 'storyboard', {
    ...persisted,
    costCents: result.usage.costCents,
  });

  return seriesId;
}

/** Fans out to the per-shot jobs. The supervisor waits on the rows, not this. */
async function runShotsStage(runId: string, userId: string, seriesId: string): Promise<string> {
  const episodeId = await firstEpisodeId(seriesId);

  await inngest.send({
    id: episodeGenerateEventId(episodeId, runId),
    name: 'episode/generate.requested',
    data: { userId, episodeId },
  });

  await recordStageResult(runId, 'shots', { episodeId, fannedOutAt: new Date().toISOString() });
  return seriesId;
}

async function runAssembleStage(
  runId: string,
  userId: string,
  seriesId: string,
): Promise<string> {
  const episodeId = await firstEpisodeId(seriesId);

  try {
    const result = await startAssembly(userId, episodeId);
    await recordStageResult(runId, 'assemble', result);
  } catch (error) {
    // A 409 here means shots failed rather than that assembly is broken. Say
    // which, and leave everything that did generate on the board.
    const message = error instanceof Error ? error.message : String(error);
    await recordStageResult(runId, 'assemble', { refused: message });
    throw new NonRetriableError(message);
  }

  return seriesId;
}
